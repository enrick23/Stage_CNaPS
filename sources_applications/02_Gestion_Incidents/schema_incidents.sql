CREATE SEQUENCE SIG.SEQ_INCIDENT START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE SIG.REF_CATEGORIE_INCIDENT (
    CODE_CATEGORIE          VARCHAR2(20) PRIMARY KEY,
    LIBELLE_CATEGORIE       VARCHAR2(100) NOT NULL,
    DELAI_RESOLUTION_HEURES NUMBER(4) DEFAULT 24,
    FLAG_ACTIF              CHAR(1) DEFAULT 'O' CHECK (FLAG_ACTIF IN ('O', 'N'))
);

CREATE TABLE SIG.INCIDENT_TICKET (
    ID_INCIDENT             NUMBER(12) PRIMARY KEY,
    CODE_CATEGORIE          VARCHAR2(20) NOT NULL,
    MATRICULE_DECLARANT     VARCHAR2(15) NOT NULL,
    TITRE_INCIDENT          VARCHAR2(150) NOT NULL,
    DESCRIPTION_DETAIL      VARCHAR2(1000),
    PRIORITE                VARCHAR2(10) DEFAULT 'MOYENNE' CHECK (PRIORITE IN ('BASSE', 'MOYENNE', 'HAUTE', 'URGENTE')),
    STATUT_INCIDENT         VARCHAR2(20) DEFAULT 'OUVERT' CHECK (STATUT_INCIDENT IN ('OUVERT', 'EN_COURS', 'RESOLU', 'FERME')),
    DATE_DECLARATION        DATE DEFAULT SYSDATE NOT NULL,
    DATE_CLOTURE            DATE,
    CONSTRAINT FK_INC_CAT FOREIGN KEY (CODE_CATEGORIE) 
        REFERENCES SIG.REF_CATEGORIE_INCIDENT(CODE_CATEGORIE)
);

CREATE INDEX SIG.IDX_INC_DECLARANT ON SIG.INCIDENT_TICKET(MATRICULE_DECLARANT);
CREATE INDEX SIG.IDX_INC_STATUT ON SIG.INCIDENT_TICKET(STATUT_INCIDENT);
CREATE INDEX SIG.IDX_INC_CAT ON SIG.INCIDENT_TICKET(CODE_CATEGORIE);

CREATE TABLE SIG.INCIDENT_COMMENTAIRE (
    ID_COMMENTAIRE          NUMBER(12) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_INCIDENT             NUMBER(12) NOT NULL,
    MATRICULE_AUTEUR        VARCHAR2(15) NOT NULL,
    MESSAGE_TEXTE           VARCHAR2(2000) NOT NULL,
    DATE_CREATION           TIMESTAMP(6) DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_COM_INCIDENT FOREIGN KEY (ID_INCIDENT) 
        REFERENCES SIG.INCIDENT_TICKET(ID_INCIDENT)
);

CREATE INDEX SIG.IDX_COM_INC ON SIG.INCIDENT_COMMENTAIRE(ID_INCIDENT);

-- Déclencheur avant insertion sur INCIDENT_TICKET pour alimenter la séquence et la date
CREATE OR REPLACE TRIGGER SIG.TRG_INCIDENT_BI
BEFORE INSERT ON SIG.INCIDENT_TICKET
FOR EACH ROW
BEGIN
    IF :NEW.ID_INCIDENT IS NULL THEN
        SELECT SIG.SEQ_INCIDENT.NEXTVAL INTO :NEW.ID_INCIDENT FROM dual;
    END IF;
    IF :NEW.DATE_DECLARATION IS NULL THEN
        :NEW.DATE_DECLARATION := SYSDATE;
    END IF;
END;
