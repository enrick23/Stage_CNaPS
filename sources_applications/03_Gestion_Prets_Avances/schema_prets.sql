CREATE SEQUENCE DRH.SEQ_DEMANDE_PRET START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE DRH.SEQ_REF_TYPE_PRET START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE DRH.REF_TYPE_PRET (
    CODE_TYPE_PRET          VARCHAR2(10) PRIMARY KEY,
    LIBELLE_TYPE_PRET       VARCHAR2(100) NOT NULL,
    DUREE_MAX_MOIS          NUMBER(3) DEFAULT 12 NOT NULL,
    PLAFOND_MONTANT         NUMBER(15,2) DEFAULT 0 NOT NULL,
    ACTIF                   CHAR(1) DEFAULT 'O' NOT NULL CHECK (ACTIF IN ('O', 'N'))
);

CREATE INDEX DRH.IDX_TYPE_PRET_LIB ON DRH.REF_TYPE_PRET(LIBELLE_TYPE_PRET);

CREATE TABLE DRH.DEMANDE_PRET (
    ID_DEMANDE              NUMBER(12) PRIMARY KEY,
    MATRICULE_AGENT         VARCHAR2(15) NOT NULL,
    CODE_TYPE_PRET          VARCHAR2(10) NOT NULL,
    MONTANT_DEMANDE         NUMBER(15,2) NOT NULL,
    MENSUALITE_RETENUE      NUMBER(12,2) DEFAULT 0 NOT NULL,
    DATE_DEMANDE            DATE DEFAULT SYSDATE NOT NULL,
    STATUT_VALIDATION       VARCHAR2(20) DEFAULT 'EN_ATTENTE' NOT NULL CHECK (STATUT_VALIDATION IN ('EN_ATTENTE', 'VALIDE', 'REJETE', 'SOLDE')),
    CONSTRAINT FK_PRET_TYPE FOREIGN KEY (CODE_TYPE_PRET) 
        REFERENCES DRH.REF_TYPE_PRET(CODE_TYPE_PRET)
);

CREATE INDEX DRH.IDX_DEM_PRET_MAT ON DRH.DEMANDE_PRET(MATRICULE_AGENT);
CREATE INDEX DRH.IDX_DEM_PRET_TYPE ON DRH.DEMANDE_PRET(CODE_TYPE_PRET);
CREATE INDEX DRH.IDX_DEM_PRET_DATE ON DRH.DEMANDE_PRET(DATE_DEMANDE);
CREATE INDEX DRH.IDX_DEM_PRET_STATUT ON DRH.DEMANDE_PRET(STATUT_VALIDATION);

-- Vue de suivi des prêts accordés
CREATE OR REPLACE VIEW DRH.V_SUIVI_PRET_AGENT AS
SELECT d.ID_DEMANDE,
       d.MATRICULE_AGENT,
       t.LIBELLE_TYPE_PRET,
       d.MONTANT_DEMANDE,
       d.STATUT_VALIDATION
  FROM DRH.DEMANDE_PRET d
  JOIN DRH.REF_TYPE_PRET t ON t.CODE_TYPE_PRET = d.CODE_TYPE_PRET
 WHERE d.STATUT_VALIDATION IN ('VALIDE', 'SOLDE');

-- Déclencheur avant insertion pour initialiser le code et la date
CREATE OR REPLACE TRIGGER DRH.TRG_REF_TYPE_PRET_BI
BEFORE INSERT ON DRH.REF_TYPE_PRET
FOR EACH ROW
BEGIN
    :NEW.CODE_TYPE_PRET := UPPER(TRIM(:NEW.CODE_TYPE_PRET));
END;
/

CREATE OR REPLACE TRIGGER DRH.TRG_BI_DEMANDE_PRET
BEFORE INSERT ON DRH.DEMANDE_PRET
FOR EACH ROW
BEGIN
    IF :NEW.ID_DEMANDE IS NULL THEN
        SELECT DRH.SEQ_DEMANDE_PRET.NEXTVAL INTO :NEW.ID_DEMANDE FROM dual;
    END IF;
    IF :NEW.DATE_DEMANDE IS NULL THEN
        :NEW.DATE_DEMANDE := SYSDATE;
    END IF;
END;
/
