-- =============================================================================
-- SCRIPT DE NETTOYAGE COMPLET DES TABLES IAM.DICO_DATA_*
-- Remet à zéro les 6 tables et réinitialise les 6 séquences à 1 (DTB000001, etc.).
-- Fonctionne même si le compte SQL Developer (ex: DEV_DEPL) n'a pas le droit DELETE.
-- =============================================================================

-- 1. SUPPRESSION DES TABLES EXISTANTES (VIDE TOUTES LES DONNÉES)
DROP TABLE IAM.DICO_DATA_INDEXES  CASCADE CONSTRAINTS;
DROP TABLE IAM.DICO_DATA_COLUMN   CASCADE CONSTRAINTS;
DROP TABLE IAM.DICO_DATA_TRIGGER  CASCADE CONSTRAINTS;
DROP TABLE IAM.DICO_DATA_FUNCTION CASCADE CONSTRAINTS;
DROP TABLE IAM.DICO_DATA_VIEW     CASCADE CONSTRAINTS;
DROP TABLE IAM.DICO_DATA_TABLE    CASCADE CONSTRAINTS;

-- 2. SUPPRESSION DES SÉQUENCES (POUR REPARTIR À 000001)
DROP SEQUENCE IAM.SEQ_DICO_DATA_TABLE;
DROP SEQUENCE IAM.SEQ_DICO_DATA_COLUMN;
DROP SEQUENCE IAM.SEQ_DICO_DATA_INDEX;
DROP SEQUENCE IAM.SEQ_DICO_DATA_TRIGGER;
DROP SEQUENCE IAM.SEQ_DICO_DATA_FUNCTION;
DROP SEQUENCE IAM.SEQ_DICO_DATA_VIEW;

-- 3. RECRÉATION DES 6 TABLES PROPRES (AVEC APP_ID VARCHAR2(36) POUR UUID LUCY)
CREATE TABLE IAM.DICO_DATA_TABLE (
    TABLE_ID            VARCHAR2(20 BYTE)   NOT NULL,
    NOM_TABLE           VARCHAR2(128 BYTE)  NOT NULL,
    TYPE_OBJET          VARCHAR2(10 BYTE)   DEFAULT 'TABLE' NOT NULL,
    DESCRIPTION         VARCHAR2(500 BYTE),
    FLAG_REF            CHAR(1 BYTE)        DEFAULT 'N',
    SCHEMAS             VARCHAR2(30 BYTE)   NOT NULL,
    APP_ID              VARCHAR2(36 BYTE),
    APP_LIBELLE         VARCHAR2(150 BYTE),
    SEQUENCE_ASSOCIEE   VARCHAR2(128 BYTE),
    CONSTRAINT DICO_DATA_TABLE_PK PRIMARY KEY (TABLE_ID),
    CONSTRAINT DICO_DATA_TABLE_UK UNIQUE (SCHEMAS, NOM_TABLE, APP_ID)
);

CREATE TABLE IAM.DICO_DATA_COLUMN (
    COLUMN_ID           VARCHAR2(20 BYTE)   NOT NULL,
    COLUMN_NAME         VARCHAR2(128 BYTE)  NOT NULL,
    ORDRE               INTEGER             DEFAULT 1,
    NIVEAU_SENSIBILITE  INTEGER             DEFAULT 1,
    TYPES               VARCHAR2(40 BYTE)   NOT NULL,
    TAILLES             VARCHAR2(20 BYTE),
    CONTRAINTE          VARCHAR2(50 BYTE),
    DEFAULT_VALUE       VARCHAR2(100 BYTE),
    DESCRIPTION         VARCHAR2(500 BYTE),
    OBSERVATION         VARCHAR2(500 BYTE),
    TABLE_ID            VARCHAR2(20 BYTE)   NOT NULL,
    CONSTRAINT DICO_DATA_COLUMN_PK PRIMARY KEY (COLUMN_ID),
    CONSTRAINT DICO_DATA_COLUMN_TABLE_FK FOREIGN KEY (TABLE_ID)
        REFERENCES IAM.DICO_DATA_TABLE (TABLE_ID) ON DELETE CASCADE
);

CREATE TABLE IAM.DICO_DATA_INDEXES (
    INDEX_ID            VARCHAR2(20 BYTE)   NOT NULL,
    NOM_INDEX           VARCHAR2(128 BYTE)  NOT NULL,
    DESCRIPTION         VARCHAR2(250 BYTE),
    COLUMN_ID           VARCHAR2(20 BYTE)   NOT NULL,
    CONSTRAINT DICO_DATA_INDEXES_PK PRIMARY KEY (INDEX_ID),
    CONSTRAINT DICO_DATA_INDEXES_COLUMN_FK FOREIGN KEY (COLUMN_ID)
        REFERENCES IAM.DICO_DATA_COLUMN (COLUMN_ID) ON DELETE CASCADE
);

CREATE TABLE IAM.DICO_DATA_TRIGGER (
    TRIGGER_ID          VARCHAR2(20 BYTE)   NOT NULL,
    NOM_TRIGGER         VARCHAR2(128 BYTE)  NOT NULL,
    DESCRIPTION         VARCHAR2(500 BYTE),
    TABLE_ID            VARCHAR2(20 BYTE)   NOT NULL,
    CONSTRAINT DICO_DATA_TRIGGER_PK PRIMARY KEY (TRIGGER_ID),
    CONSTRAINT DICO_DATA_TRIGGER_TABLE_FK FOREIGN KEY (TABLE_ID)
        REFERENCES IAM.DICO_DATA_TABLE (TABLE_ID) ON DELETE CASCADE
);

CREATE TABLE IAM.DICO_DATA_FUNCTION (
    FUNCTION_ID         VARCHAR2(20 BYTE)   NOT NULL,
    NOM_FUNCTION        VARCHAR2(128 BYTE)  NOT NULL,
    DESCRIPTION         VARCHAR2(500 BYTE),
    TABLE_ID            VARCHAR2(20 BYTE)   NOT NULL,
    APP_ID              VARCHAR2(36 BYTE),
    CONSTRAINT DICO_DATA_FUNCTION_PK PRIMARY KEY (FUNCTION_ID),
    CONSTRAINT DICO_DATA_FUNCTION_TABLE_FK FOREIGN KEY (TABLE_ID)
        REFERENCES IAM.DICO_DATA_TABLE (TABLE_ID) ON DELETE CASCADE
);

CREATE TABLE IAM.DICO_DATA_VIEW (
    VIEW_ID             VARCHAR2(20 BYTE)   NOT NULL,
    NOM_VIEW            VARCHAR2(128 BYTE)  NOT NULL,
    DESCRIPTION         VARCHAR2(500 BYTE),
    SCRIPT              VARCHAR2(4000 BYTE),
    TABLE_ID            VARCHAR2(20 BYTE)   NOT NULL,
    APP_ID              VARCHAR2(36 BYTE),
    CONSTRAINT DICO_DATA_VIEW_PK PRIMARY KEY (VIEW_ID),
    CONSTRAINT DICO_DATA_VIEW_TABLE_FK FOREIGN KEY (TABLE_ID)
        REFERENCES IAM.DICO_DATA_TABLE (TABLE_ID) ON DELETE CASCADE
);

-- 4. RECRÉATION DES SÉQUENCES À PARTIR DE 1
CREATE SEQUENCE IAM.SEQ_DICO_DATA_TABLE    START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE IAM.SEQ_DICO_DATA_COLUMN   START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE IAM.SEQ_DICO_DATA_INDEX    START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE IAM.SEQ_DICO_DATA_TRIGGER  START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE IAM.SEQ_DICO_DATA_FUNCTION START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE IAM.SEQ_DICO_DATA_VIEW     START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

-- 5. RECRÉATION DES TRIGGERS D'AUTO-GÉNÉRATION DES ID
CREATE OR REPLACE TRIGGER IAM.TRG_DICO_DATA_TABLE_BI
BEFORE INSERT ON IAM.DICO_DATA_TABLE FOR EACH ROW
WHEN (NEW.TABLE_ID IS NULL)
BEGIN
    SELECT 'DTB' || LPAD(IAM.SEQ_DICO_DATA_TABLE.NEXTVAL, 6, '0') INTO :NEW.TABLE_ID FROM dual;
END;
/

