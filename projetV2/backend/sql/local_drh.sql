-- Execute while connected to the local DRH schema owner.
-- The application user (application.properties: DEV_DEPL) receives read access below.

CREATE TABLE DRH_DIRECTION (
    CODE_DIRECTION    VARCHAR2(10) PRIMARY KEY,
    LIBELLE_DIRECTION VARCHAR2(100) NOT NULL,
    CODE_ABREV        VARCHAR2(20),
    FLAG_ACTIF        CHAR(1)
);

CREATE TABLE DRH_SERVICE (
    CODE_SERVICE    VARCHAR2(8) PRIMARY KEY,
    LIBELLE_SERVICE VARCHAR2(150) NOT NULL,
    CODE_ACTIF      CHAR(1)
);

CREATE TABLE DRH_FONCTION (
    CODE_FONCTION    VARCHAR2(10) PRIMARY KEY,
    LIBELLE_FONCTION VARCHAR2(150) NOT NULL
);

CREATE TABLE DRH_RENSEIGNEMENT_AGENT (
    AGENT_MATRICULE VARCHAR2(10) PRIMARY KEY,
    NOM             VARCHAR2(100),
    PRENOMS         VARCHAR2(150)
);

CREATE TABLE DRH_RENS_FONCTION (
    ID_RENS_FONCTION NUMBER(10) PRIMARY KEY,
    AGENT_MATRICULE  VARCHAR2(10) NOT NULL,
    CODE_DIRECTION   VARCHAR2(10) NOT NULL,
    CODE_SERVICE     VARCHAR2(8) NOT NULL,
    CODE_FONCTION    VARCHAR2(10) NOT NULL,
    DATE_FIN_ESSAI   DATE,
    CONSTRAINT FK_LOCAL_RF_AGENT FOREIGN KEY (AGENT_MATRICULE)
        REFERENCES DRH_RENSEIGNEMENT_AGENT (AGENT_MATRICULE),
    CONSTRAINT FK_LOCAL_RF_DIRECTION FOREIGN KEY (CODE_DIRECTION)
        REFERENCES DRH_DIRECTION (CODE_DIRECTION),
    CONSTRAINT FK_LOCAL_RF_SERVICE FOREIGN KEY (CODE_SERVICE)
        REFERENCES DRH_SERVICE (CODE_SERVICE),
    CONSTRAINT FK_LOCAL_RF_FONCTION FOREIGN KEY (CODE_FONCTION)
        REFERENCES DRH_FONCTION (CODE_FONCTION)
);

