

CREATE TABLE IAM.BESOIN_SERVICE (
    ID_BESOIN_SERVICE NUMBER(2) PRIMARY KEY,
    LIBELLE           VARCHAR2(20) NOT NULL UNIQUE
);

INSERT INTO IAM.BESOIN_SERVICE (ID_BESOIN_SERVICE, LIBELLE) VALUES (1, 'CONSERVER');
INSERT INTO IAM.BESOIN_SERVICE (ID_BESOIN_SERVICE, LIBELLE) VALUES (2, 'MODIFIER');
INSERT INTO IAM.BESOIN_SERVICE (ID_BESOIN_SERVICE, LIBELLE) VALUES (3, 'SUPPRIMER');

ALTER TABLE IAM.RV_ACC ADD (ID_BESOIN_SERVICE NUMBER(2));

UPDATE IAM.RV_ACC
SET ID_BESOIN_SERVICE = CASE BESOIN_SERVICE
    WHEN 'CONSERVER' THEN 1
    WHEN 'MODIFIER' THEN 2
    WHEN 'SUPPRIMER' THEN 3
END
WHERE BESOIN_SERVICE IS NOT NULL;

ALTER TABLE IAM.RV_ACC
    ADD CONSTRAINT FK_RV_ACC_BESOIN_SERVICE
    FOREIGN KEY (ID_BESOIN_SERVICE)
    REFERENCES IAM.BESOIN_SERVICE(ID_BESOIN_SERVICE);

ALTER TABLE IAM.RV_ACC DROP COLUMN BESOIN_SERVICE CASCADE CONSTRAINTS;

ALTER TABLE IAM.RV_ACC_HISTO ADD (ID_BESOIN_SERVICE NUMBER(2));

UPDATE IAM.RV_ACC_HISTO
SET ID_BESOIN_SERVICE = CASE BESOIN_SERVICE
    WHEN 'CONSERVER' THEN 1
    WHEN 'MODIFIER' THEN 2
    WHEN 'SUPPRIMER' THEN 3
END
WHERE BESOIN_SERVICE IS NOT NULL;

ALTER TABLE IAM.RV_ACC_HISTO
    ADD CONSTRAINT FK_RV_ACC_HISTO_BESOIN_SERVICE
    FOREIGN KEY (ID_BESOIN_SERVICE)
    REFERENCES IAM.BESOIN_SERVICE(ID_BESOIN_SERVICE);

ALTER TABLE IAM.RV_ACC_HISTO DROP COLUMN BESOIN_SERVICE CASCADE CONSTRAINTS;

CREATE INDEX IDX_RV_ACC_DETAIL_BESOIN ON IAM.RV_ACC (ID_BESOIN_SERVICE);
CREATE INDEX IDX_RV_ACC_HISTO_BESOIN ON IAM.RV_ACC_HISTO (ID_BESOIN_SERVICE);