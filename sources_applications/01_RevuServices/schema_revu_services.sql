CREATE TABLE IAM.APP_DMD_AGENT_CONCERNE (
    ID_DMD_AGENT_CONCERNE   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODE_DMD                VARCHAR2(100) NOT NULL,
    MATRICULE               VARCHAR2(10) NOT NULL,
    DATE_CREATION           TIMESTAMP(6) DEFAULT SYSDATE
);

CREATE INDEX IAM.IDX_AGENT_CONCERNE_DMD ON IAM.APP_DMD_AGENT_CONCERNE(CODE_DMD);
CREATE INDEX IAM.IDX_AGENT_CONCERNE_MAT ON IAM.APP_DMD_AGENT_CONCERNE(MATRICULE);


CREATE TABLE IAM.APP_DMD_PRIVILEGE_DETAIL (
    ID_APP_DMD_PRIVILEGE    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_DMD_AGENT_CONCERNE   NUMBER NOT NULL,
    AGENT_MATRICULE         VARCHAR2(10) NOT NULL,
    LIBELLE_FONCTION        VARCHAR2(100),
    CODE_SERVICE            VARCHAR2(8),
    SECTION                 VARCHAR2(20) NOT NULL,
    APPLICATION             VARCHAR2(50),
    CATEGORIE               VARCHAR2(50),
    TYPE_CATEGORIE          VARCHAR2(50),
    BESOIN_SERVICE          VARCHAR2(20) CHECK (BESOIN_SERVICE IN ('CONSERVER', 'MODIFIER', 'SUPPRIMER')),
    MOTIF_SUPPRESSION       VARCHAR2(500),
    ID_LIGNE_ORIGINE        NUMBER,
    DATE_CORRECTION         TIMESTAMP(6),
    CORRIGE_PAR             VARCHAR2(100),
    CONSTRAINT FK_PRIV_AGENT FOREIGN KEY (ID_DMD_AGENT_CONCERNE) 
        REFERENCES IAM.APP_DMD_AGENT_CONCERNE(ID_DMD_AGENT_CONCERNE)
);

CREATE INDEX IAM.IDX_PRIV_AGENT ON IAM.APP_DMD_PRIVILEGE_DETAIL(ID_DMD_AGENT_CONCERNE);
CREATE INDEX IAM.IDX_PRIV_MATRICULE ON IAM.APP_DMD_PRIVILEGE_DETAIL(AGENT_MATRICULE);


CREATE TABLE IAM.APP_DMD_PRIVILEGE_HISTO (
    ID_HISTO                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_APP_DMD_PRIVILEGE    NUMBER NOT NULL,
    ID_DMD_AGENT_CONCERNE   NUMBER NOT NULL,
    AGENT_MATRICULE         VARCHAR2(10) NOT NULL,
    LIBELLE_FONCTION        VARCHAR2(100),
    CODE_SERVICE            VARCHAR2(8),
    SECTION                 VARCHAR2(20),
    APPLICATION             VARCHAR2(50),
    CATEGORIE               VARCHAR2(50),
    TYPE_CATEGORIE          VARCHAR2(50),
    BESOIN_SERVICE          VARCHAR2(20),
    MOTIF_SUPPRESSION       VARCHAR2(500),
    DATE_ACTION             TIMESTAMP(6) DEFAULT SYSDATE,
    TYPE_ACTION             VARCHAR2(20) CHECK (TYPE_ACTION IN ('CREATION', 'MODIFICATION', 'SUPPRESSION')),
    ACTION_PAR              VARCHAR2(100)
);

CREATE INDEX IAM.IDX_HISTO_PRIVILEGE ON IAM.APP_DMD_PRIVILEGE_HISTO(ID_APP_DMD_PRIVILEGE);

-- Déclencheur d'audit automatique
CREATE OR REPLACE TRIGGER IAM.TRG_PRIVILEGE_AUDIT
AFTER UPDATE OR DELETE ON IAM.APP_DMD_PRIVILEGE_DETAIL
FOR EACH ROW
BEGIN
    INSERT INTO IAM.APP_DMD_PRIVILEGE_HISTO (
        ID_APP_DMD_PRIVILEGE, ID_DMD_AGENT_CONCERNE, AGENT_MATRICULE,
        LIBELLE_FONCTION, CODE_SERVICE, SECTION, APPLICATION,
        CATEGORIE, TYPE_CATEGORIE, BESOIN_SERVICE, MOTIF_SUPPRESSION,
        DATE_ACTION, TYPE_ACTION, ACTION_PAR
    ) VALUES (
        :OLD.ID_APP_DMD_PRIVILEGE, :OLD.ID_DMD_AGENT_CONCERNE, :OLD.AGENT_MATRICULE,
        :OLD.LIBELLE_FONCTION, :OLD.CODE_SERVICE, :OLD.SECTION, :OLD.APPLICATION,
        :OLD.CATEGORIE, :OLD.TYPE_CATEGORIE, :OLD.BESOIN_SERVICE, :OLD.MOTIF_SUPPRESSION,
        SYSDATE, CASE WHEN DELETING THEN 'SUPPRESSION' ELSE 'MODIFICATION' END, USER
    );
END;
