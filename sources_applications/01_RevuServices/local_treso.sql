-- Execute while connected to the local TRESO schema owner.
-- The application user (application.properties: DEV_DEPL) receives access below.

CREATE TABLE CNAPS_USER (
    USERNAME       VARCHAR2(30) PRIMARY KEY,
    USER_MATRICULE VARCHAR2(10) NOT NULL UNIQUE
);

CREATE TABLE CPT_MENU_SECTION (
    SECTION     VARCHAR2(20) PRIMARY KEY,
    SECTION_LIB VARCHAR2(100) NOT NULL
);

CREATE TABLE CPT_MENU_SECTION_USERS (
    SECTION_USER VARCHAR2(30) NOT NULL,
    SECTION      VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_LOCAL_MENU_SECTION_USERS PRIMARY KEY (SECTION_USER, SECTION),
    CONSTRAINT FK_LOCAL_MSU_USER FOREIGN KEY (SECTION_USER)
        REFERENCES CNAPS_USER (USERNAME),
    CONSTRAINT FK_LOCAL_MSU_SECTION FOREIGN KEY (SECTION)
        REFERENCES CPT_MENU_SECTION (SECTION)
);

CREATE TABLE CPT_MENU (
    MENU_CODE        VARCHAR2(50) PRIMARY KEY,
    MENU_LIBELLE     VARCHAR2(100) NOT NULL,
    MENU_DESCRIPTION VARCHAR2(500),
    MENU_FMX         VARCHAR2(100),
    SECTION          VARCHAR2(20),
    CONSTRAINT FK_LOCAL_MENU_SECTION FOREIGN KEY (SECTION)
        REFERENCES CPT_MENU_SECTION (SECTION)
);

